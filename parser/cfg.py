PRODUCTIONS: List[Production] = [
    Production(rid, lhs, tuple(rhs))
    for rid, lhs, rhs in RAW_PRODUCTIONS
]

PRODUCTIONS_BY_ID: Dict[int, Production] = {p.rule_id: p for p in PRODUCTIONS}

PRODUCTIONS_BY_LHS: Dict[str, List[Production]] = {}
for prod in PRODUCTIONS:
    PRODUCTIONS_BY_LHS.setdefault(prod.lhs, []).append(prod)

NON_TERMINALS: Set[str] = {p.lhs for p in PRODUCTIONS}
TERMINALS: Set[str] = {
    sym
    for p in PRODUCTIONS
    for sym in p.rhs
    if sym not in NON_TERMINALS and sym != NULL
}
